const ts = require("@typescript/typescript6");
const path = require("node:path");
const {
  createContractProgram,
  writeOrCheckContract,
} = require("./contract-generation.cjs");

const source = path.resolve(__dirname, "../src/lib/vendor-onboarding/schemas.ts");
const target = path.resolve(__dirname, "../../vendor-onboarding-contracts/index.d.ts");
const program = createContractProgram([source]);
const checker = program.getTypeChecker();
const file = program.getSourceFile(source);
const errors = program.getSemanticDiagnostics(file);
if (errors.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(errors, {getCurrentDirectory: () => process.cwd(), getCanonicalFileName: x => x, getNewLine: () => "\n"}));
const exportsList = checker.getExportsOfModule(checker.getSymbolAtLocation(file)).filter(s => s.flags & ts.SymbolFlags.TypeAlias);
const native = {
  SellerSummary: 'Pick<SellerDTO, "id" | "name" | "handle" | "status" | "currency_code">',
  ApplicantSummary: 'Pick<HttpTypes.StoreCustomer, "id" | "email" | "first_name" | "last_name">',
};
const named = new Map(exportsList.map(s => [checker.getDeclaredTypeOfSymbol(s), s.name]));
function render(type, root, depth = 0) {
  if (depth > 20) throw new Error("Recursive transport type");
  if (named.has(type) && named.get(type) !== root) return named.get(type);
  if (type.flags & ts.TypeFlags.StringLiteral) return JSON.stringify(type.value);
  if (type.flags & ts.TypeFlags.NumberLiteral) return String(type.value);
  if (type.flags & ts.TypeFlags.BooleanLiteral) return type.intrinsicName;
  if (type.flags & ts.TypeFlags.String) return "string";
  if (type.flags & ts.TypeFlags.Number) return "number";
  if (type.flags & ts.TypeFlags.Boolean) return "boolean";
  if (type.flags & ts.TypeFlags.Null) return "null";
  if (type.isUnion()) return type.types.filter(t => !(t.flags & ts.TypeFlags.Undefined)).map(t => render(t, root, depth + 1)).join(" | ");
  if (checker.isArrayType(type)) return `Array<${render(checker.getTypeArguments(type)[0], root, depth + 1)}>`;
  if (type.flags & ts.TypeFlags.Object) {
    if (type.getCallSignatures().length || type.getConstructSignatures().length || type.getStringIndexType()) throw new Error("Non-JSON transport object");
    return `{ ${type.getProperties().map(p => `${JSON.stringify(p.name)}${p.flags & ts.SymbolFlags.Optional ? "?" : ""}: ${render(checker.getTypeOfSymbolAtLocation(p, file), root, depth + 1)};`).join(" ")} }`;
  }
  throw new Error(`Unsupported transport type: ${checker.typeToString(type)}`);
}
const result = '// Generated by packages/api/scripts/generate-onboarding-contracts.cjs. Do not edit.\nimport type { SellerDTO } from "@mercurjs/types";\nimport type { HttpTypes } from "@medusajs/types";\n\n' + exportsList.map(s => `export type ${s.name} = ${native[s.name] || render(checker.getDeclaredTypeOfSymbol(s), s.name)};`).join("\n") + "\n";

writeOrCheckContract(
  target,
  result,
  "Onboarding contracts are stale; run pnpm contracts:generate",
);
